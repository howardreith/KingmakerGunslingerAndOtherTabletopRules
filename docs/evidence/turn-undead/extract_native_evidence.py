"""Sanitized, hash-bound extract of Turn Undead loader-compat runs.

Reads the lab's retained machine-generated records (session-summary.json, each
launch-summary.json and harness-result.json) and writes reviewable JSON under
docs/evidence/turn-undead/. Raw logs, saves and profiles stay in the lab; each
extract names the SHA-256 of every source record it was derived from, so a
reviewer with lab access can verify it. Absolute machine paths are dropped.

Usage (run from the repository root):
  python -I -B docs/evidence/turn-undead/extract_native_evidence.py <evidence-root> <fixture-dir>
"""
import hashlib
import json
import os
import sys

RUNS = [
    "20261128T094042Z-umm-0.31.1-turn-undead-first",
    "20261128T095145Z-umm-0.31.1-turn-undead-first",
    "20261128T095946Z-umm-0.31.1-turn-undead-first",
    "20261128T100756Z-umm-0.31.1-turn-undead-first",
    "20261128T104421Z-umm-0.31.1-turn-undead-first",
    "20261128T105226Z-umm-0.31.1-turn-undead-first",
    "20261128T105459Z-umm-0.31.1-turn-undead-cotw-contracts",
    "20261128T112755Z-umm-0.31.1-turn-undead-first",
    "20261128T113029Z-umm-0.31.1-turn-undead-cotw-contracts",
    "20261128T113902Z-umm-0.31.1-turn-undead-first",
    "20261128T114135Z-umm-0.31.1-turn-undead-cotw-contracts",
]
SESSION_FIELDS = [
    "sessionId", "session", "loaderProfile", "candidateZipSha256", "candidateDllSha256", "admission", "git",
    "status", "runtimeLease", "transactionId", "ownership", "registryRestore", "registryRestored",
    "ownerIntegrity", "ownerSavesUnchanged", "ownerInstallUnchanged", "ownerSaveFiles", "scenarioPassed",
    "transactionSucceeded", "candidateVersion", "hostConflict",
]
CONTRACT_KEYS = ["engine", "methods", "sources", "feat", "flight", "channelResistance4", "nativeFacts", "callOfTheWild"]


def sha256(path):
    with open(path, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def load(path):
    with open(path, encoding="utf-8-sig") as handle:
        return json.load(handle)


def without_trace(probe):
    return {key: value for key, value in probe.items() if key != "trace"}


def turn_saves(probe):
    return [event for event in probe.get("trace", []) if event.get("what") == "save"]


def extract_run(root, run):
    base = os.path.join(root, run)
    summary_path = os.path.join(base, "session-summary.json")
    summary = load(summary_path)
    record = {key: summary.get(key) for key in SESSION_FIELDS}
    record["registryVerification"] = {key: (summary.get("registryVerification") or {}).get(key)
                                      for key in ("status", "sha256", "backupSha256")}
    loader = summary.get("loaderInstall") or {}
    record["loader"] = {"profile": loader.get("profile"), "ummVersion": loader.get("ummVersion"),
                        "harmonyVersion": loader.get("harmonyVersion"), "files": loader.get("files")}
    record["stagedMods"] = summary.get("stagedMods")
    record["sourceRecords"] = {"session-summary.json": sha256(summary_path)}
    launches = []
    for launch in summary.get("launches", []):
        label = launch.get("label")
        entry = {key: launch.get(key) for key in ("label", "verdict", "problems", "seconds", "identity", "log", "harness")}
        launch_dir = os.path.join(base, label)
        for name in ("launch-summary.json", os.path.join("harness", "harness-result.json")):
            path = os.path.join(launch_dir, name)
            if os.path.exists(path):
                record["sourceRecords"][label + "/" + name.replace(os.sep, "/")] = sha256(path)
        result_path = os.path.join(launch_dir, "harness", "harness-result.json")
        if os.path.exists(result_path):
            result = load(result_path)
            entry["harnessStatus"] = result.get("status")
            entry["harnessFailure"] = result.get("failure")
            entry["isolationRestored"] = result.get("isolationRestored")
            entry["steps"] = result.get("steps")
            probes = {}
            for key, value in result.items():
                if key.startswith("kmgTurnUndead_") and isinstance(value, dict):
                    probe = without_trace(value)
                    probe["turnSaves"] = turn_saves(value)
                    probe["damageEvents"] = [e for e in value.get("trace", []) if e.get("what") in ("damage", "heal")]
                    probes[key[len("kmgTurnUndead_"):]] = probe
            entry["probes"] = probes
        launches.append(entry)
    record["launches"] = launches
    return record, summary


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    root, fixtures = sys.argv[1], sys.argv[2]
    out_dir = os.path.dirname(os.path.abspath(__file__))
    fixture = os.path.join(fixtures, "KMCS_AFTER_NORMAL_012_MODONLY.zks")
    runs = []
    for run in RUNS:
        record, _ = extract_run(root, run)
        runs.append(record)
    document = {
        "schema": "kmg.turn-undead.native-runs.v1",
        "note": "Machine-generated by docs/evidence/turn-undead/extract_native_evidence.py from the lab's retained "
                "loader-compat records; failed attempts are retained. Raw logs, saves and profiles stay in the lab.",
        "referenceFixture": {"save": "KMCS_AFTER_NORMAL_012_MODONLY.zks", "sha256AtExtraction": sha256(fixture),
                             "provenance": "SHA-256 of the reference fixture file in the lab fixture directory, read when this "
                                           "extract was generated; each session staged its own copy of that file into its "
                                           "isolated profile (the staged copies are not hashed here)."},
        "observer": "tools/LoaderCompatHarness (TurnUndeadProbes.cs, TurnUndeadContractProbes.cs) at the run's git commit; "
                    "harness DLL hash in stagedMods.KmgLoaderCompatHarness",
        "runs": runs,
    }
    with open(os.path.join(out_dir, "native-runs.json"), "w", encoding="utf-8", newline="\n") as handle:
        json.dump(document, handle, indent=1, sort_keys=False)
        handle.write("\n")
    # Contract extracts (vanilla and CotW) from the passing runs.
    for run, name in (("20261128T113902Z-umm-0.31.1-turn-undead-first", "contracts-vanilla.json"),
                      ("20261128T114135Z-umm-0.31.1-turn-undead-cotw-contracts", "contracts-cotw.json")):
        record = next(r for r in runs if r["sessionId"] == run)
        probe = record["launches"][0]["probes"]["contracts"]
        contract = {
            "schema": "kmg.turn-undead.contracts.v1",
            "run": run, "loaderProfile": record["loaderProfile"],
            "candidate": {"producerCommit": record["admission"]["producerCommit"],
                          "packageSha256": record["admission"]["packageSha256"],
                          "dllSha256": record["admission"]["dllSha256"]},
            "activeMods": record["launches"][0]["identity"].get("activeMods"),
            "sourceRecords": record["sourceRecords"],
            "problems": probe.get("problems"),
            "moduleStatus": probe.get("moduleStatus"), "cotw": probe.get("cotw"),
        }
        for key in CONTRACT_KEYS:
            contract[key] = probe.get(key)
        with open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\n") as handle:
            json.dump(contract, handle, indent=1)
            handle.write("\n")
    print("wrote native-runs.json, contracts-vanilla.json, contracts-cotw.json")


if __name__ == "__main__":
    main()
